#!/usr/bin/env python3
"""Embed the project website into the kernel for live-browser use."""
from __future__ import annotations

import sys
from pathlib import Path

FILES = [
    ("website/index.html", "www/index.html", 1),
    ("website/docs.html", "www/docs.html", 1),
    ("website/install.html", "www/install.html", 1),
    ("website/manual.html", "www/manual.html", 1),
    ("README.md", "README.TXT", 0),
]


def array_name(index: int) -> str:
    return "site_file_%d" % index


def emit_bytes(data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    return "\n".join(lines)


def main() -> None:
    out_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "build")
    out_dir.mkdir(parents=True, exist_ok=True)

    c = []
    c.append("/* generated by tools/embed_site.py; do not edit */")
    c.append('#include "site_data.h"')
    c.append("")

    entries = []
    for i, (src_name, guest_path, is_html) in enumerate(FILES):
        src = Path(src_name)
        if not src.exists():
            raise SystemExit("missing website source: %s" % src_name)
        data = src.read_bytes() + b"\x00"
        name = array_name(i)
        c.append("static const unsigned char %s[] = {" % name)
        c.append(emit_bytes(data))
        c.append("};")
        c.append("")
        entries.append((guest_path, name, len(data) - 1, is_html))

    c.append("const site_file_t g_site_files[] = {")
    for guest_path, name, size, is_html in entries:
        c.append('    { "%s", %s, %d, %d },' % (guest_path, name, size, is_html))
    c.append("};")
    c.append("const unsigned int g_site_file_count = %d;" % len(entries))
    c.append("")

    (out_dir / "site_data.c").write_text("\n".join(c), encoding="ascii")
    (out_dir / "site_data.h").write_text(
        "/* generated by tools/embed_site.py; do not edit */\n"
        "#ifndef BYTEOS_SITE_DATA_H\n"
        "#define BYTEOS_SITE_DATA_H\n\n"
        "typedef struct {\n"
        "    const char *path;\n"
        "    const unsigned char *data;\n"
        "    unsigned int size;\n"
        "    unsigned int html;\n"
        "} site_file_t;\n\n"
        "extern const site_file_t g_site_files[];\n"
        "extern const unsigned int g_site_file_count;\n\n"
        "#endif\n",
        encoding="ascii",
    )
    print("embedded %d website files in %s" % (len(entries), out_dir / "site_data.c"))


if __name__ == "__main__":
    main()
