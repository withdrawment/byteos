#!/usr/bin/env python3
"""Convert a binary file into a C byte array source file."""
from __future__ import annotations

import sys
from pathlib import Path


def emit_bytes(data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 4:
        raise SystemExit("usage: bin2c.py <input> <output.c> <symbol>")
    src = Path(sys.argv[1])
    out = Path(sys.argv[2])
    symbol = sys.argv[3]
    data = src.read_bytes()
    text = (
        "/* generated by tools/bin2c.py; do not edit */\n"
        "#include <stddef.h>\n\n"
        "const unsigned char %s[] = {\n%s\n};\n"
        "const unsigned int %s_size = %d;\n"
        % (symbol, emit_bytes(data), symbol, len(data))
    )
    out.write_text(text, encoding="ascii")
    print("embedded %s (%d bytes) as %s in %s" %
          (src.name, len(data), symbol, out.name))


if __name__ == "__main__":
    main()
